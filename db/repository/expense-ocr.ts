import { DEFAULT_EXPENSE_TYPE, normalizeExpenseType, type ExpenseType } from "@/lib/expenses/constants";

export type ExpenseOcrStatus = "pending" | "queued" | "processing" | "completed" | "failed";

export type ExpenseDraftOcrSuggestion = {
  amountExclVatCents?: number | null;
  vatRate?: number | null;
  expenseDate?: Date | null;
  dueDate?: Date | null;
  supplierRef?: string | null;
  notes?: string | null;
  supplierName?: string | null;
  categoryName?: string | null;
  supplierId?: string | null;
  categoryId?: string | null;
  expenseType?: ExpenseType | null;
  extractedText?: string | null;
  confidence?: number | null;
  extraction?: Record<string, unknown> | null;
};

type ExpenseOcrContext = {
  expense: Record<string, unknown>;
  attachment: Record<string, unknown>;
};

function isValidObjectId(value: string) {
  return mongoose.Types.ObjectId.isValid(value);
}

function toObjectId(value: string) {
  return new mongoose.Types.ObjectId(value);
}

function toObjectIdString(value: unknown) {
  if (typeof value === "string" && isValidObjectId(value)) {
    return value;
  }

  if (value instanceof mongoose.Types.ObjectId) {
    return String(value);
  }

  if (value && typeof value === "object") {
    const nestedId = (value as { _id?: unknown })._id;
    if (typeof nestedId === "string" && isValidObjectId(nestedId)) {
      return nestedId;
    }
    if (nestedId instanceof mongoose.Types.ObjectId) {
      return String(nestedId);
    }
  }

  return null;
}

function normalizeText(value: string) {
  return value
    .normalize("NFKD")
    .replace(/[^\w\s]/g, " ")
    .replace(/_/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

function toCleanString(value: unknown) {
  if (typeof value !== "string") {
    return null;
  }

  const trimmed = value.trim();
  return trimmed ? trimmed : null;
}

function toPositiveInteger(value: unknown) {
  if (typeof value !== "number" || !Number.isFinite(value)) {
    return null;
  }

  const normalized = Math.max(0, Math.round(value));
  return normalized > 0 ? normalized : null;
}

function toVatRate(value: unknown) {
  if (typeof value !== "number" || !Number.isFinite(value)) {
    return null;
  }

  const normalized = Math.round(value * 100) / 100;
  if (normalized < 0 || normalized > 100) {
    return null;
  }

  return normalized;
}

function toDateOrNull(value: unknown) {
  if (!value) {
    return null;
  }

  const date = value instanceof Date ? value : new Date(String(value));
  return Number.isNaN(date.getTime()) ? null : date;
}

function isBlank(value: unknown) {
  return typeof value !== "string" || value.trim().length === 0;
}

function isAutoGeneratedDraftExpenseDate(expense: Record<string, unknown>) {
  const expenseDate = toDateOrNull(expense.expenseDate);
  const createdAt = toDateOrNull(expense.createdAt);

  if (!expenseDate || !createdAt) {
    return false;
  }

  return Math.abs(expenseDate.getTime() - createdAt.getTime()) <= 5 * 60 * 1000;
}

function isAutoGeneratedDraftDueDate(expense: Record<string, unknown>) {
  const expenseDate = toDateOrNull(expense.expenseDate);
  const dueDate = toDateOrNull(expense.dueDate);

  if (!expenseDate || !dueDate) {
    return false;
  }

  const expectedDueTime = expenseDate.getTime() + 7 * 24 * 60 * 60 * 1000;
  return Math.abs(dueDate.getTime() - expectedDueTime) <= 5 * 60 * 1000;
}

async function resolveSupplierId(params: { createdBy: string; supplierName?: string | null; supplierId?: string | null }) {
  if (params.supplierId && isValidObjectId(params.supplierId)) {
    return params.supplierId;
  }

  const target = normalizeText(params.supplierName || "");
  if (!target) {
    return null;
  }

  const suppliers = await Supplier.find({ user: params.createdBy })
    .select("_id fullName companyName contactName")
    .lean<Array<Record<string, unknown>>>();

  let bestMatch: { id: string; score: number } | null = null;

  for (const supplier of suppliers) {
    const labels = [supplier.fullName, supplier.companyName, supplier.contactName]
      .map((entry) => toCleanString(entry))
      .filter((entry): entry is string => Boolean(entry));

    for (const label of labels) {
      const normalizedLabel = normalizeText(label);
      if (!normalizedLabel) {
        continue;
      }

      let score = 0;
      if (normalizedLabel === target) {
        score = 1;
      } else if (normalizedLabel.includes(target) || target.includes(normalizedLabel)) {
        score = 0.8;
      } else {
        const targetTokens = new Set(target.split(" "));
        const labelTokens = normalizedLabel.split(" ");
        const overlap = labelTokens.filter((token) => targetTokens.has(token)).length;
        score = overlap / Math.max(targetTokens.size, labelTokens.length, 1);
      }

      if (!bestMatch || score > bestMatch.score) {
        bestMatch = {
          id: String(supplier._id),
          score,
        };
      }
    }
  }

  return bestMatch && bestMatch.score >= 0.75 ? bestMatch.id : null;
}

async function resolveCategoryId(params: { companyId: string; categoryName?: string | null; categoryId?: string | null }) {
  if (params.categoryId && isValidObjectId(params.categoryId)) {
    return params.categoryId;
  }

  const target = normalizeText(params.categoryName || "");
  if (!target) {
    return null;
  }

  const categories = await ExpenseCategory.find({
    companyId: params.companyId,
    isEnabled: true,
  })
    .select("_id name nameEn nameFr slug canonicalKey")
    .lean<Array<Record<string, unknown>>>();

  let bestMatch: { id: string; score: number } | null = null;

  for (const category of categories) {
    const labels = [category.name, category.nameEn, category.nameFr, category.slug, category.canonicalKey]
      .map((entry) => toCleanString(entry))
      .filter((entry): entry is string => Boolean(entry));

    for (const label of labels) {
      const normalizedLabel = normalizeText(label);
      if (!normalizedLabel) {
        continue;
      }

      let score = 0;
      if (normalizedLabel === target) {
        score = 1;
      } else if (normalizedLabel.includes(target) || target.includes(normalizedLabel)) {
        score = 0.8;
      } else {
        const targetTokens = new Set(target.split(" "));
        const labelTokens = normalizedLabel.split(" ");
        const overlap = labelTokens.filter((token) => targetTokens.has(token)).length;
        score = overlap / Math.max(targetTokens.size, labelTokens.length, 1);
      }

      if (!bestMatch || score > bestMatch.score) {
        bestMatch = {
          id: String(category._id),
          score,
        };
      }
    }
  }

  return bestMatch && bestMatch.score >= 0.6 ? bestMatch.id : null;
}

export async function getDraftExpenseOcrContext(params: {
  companyId: string;
  expenseId: string;
  attachmentId?: string;
}): Promise<{ success: true; data: ExpenseOcrContext } | { success: false; message: string }> {
  await ConnectDb();

  if (!isValidObjectId(params.companyId) || !isValidObjectId(params.expenseId)) {
    return { success: false, message: "Invalid OCR draft context" };
  }

  const expense = await Expense.findOne({
    _id: params.expenseId,
    companyId: params.companyId,
    deletedAt: null,
  }).lean<Record<string, unknown> | null>();

  if (!expense) {
    return { success: false, message: "Draft expense not found" };
  }

  const attachmentQuery: Record<string, unknown> = {
    companyId: params.companyId,
    expenseId: params.expenseId,
  };

  if (params.attachmentId && isValidObjectId(params.attachmentId)) {
    attachmentQuery._id = params.attachmentId;
  }

  const attachment = await ExpenseAttachment.findOne(attachmentQuery)
    .sort({ createdAt: -1 })
    .lean<Record<string, unknown> | null>();

  if (!attachment) {
    return { success: false, message: "Expense attachment not found" };
  }

  return {
    success: true,
    data: {
      expense,
      attachment,
    },
  };
}

export async function markExpenseOcrStatus(params: {
  companyId: string;
  expenseId: string;
  status: ExpenseOcrStatus;
  error?: string | null;
  extractedText?: string | null;
  confidence?: number | null;
  extraction?: Record<string, unknown> | null;
}) {
  await ConnectDb();

  if (!isValidObjectId(params.companyId) || !isValidObjectId(params.expenseId)) {
    return { success: false as const, message: "Invalid OCR status context" };
  }

  const now = new Date();
  const updatePayload: Record<string, unknown> = {
    ocrStatus: params.status,
    ocrError: params.error?.trim() || null,
  };

  if (params.status === "queued") {
    updatePayload.ocrQueuedAt = now;
  }

  if (params.status === "processing") {
    updatePayload.ocrStartedAt = now;
    updatePayload.ocrFailedAt = null;
  }

  if (params.status === "completed") {
    updatePayload.ocrCompletedAt = now;
    updatePayload.ocrFailedAt = null;
  }

  if (params.status === "failed") {
    updatePayload.ocrFailedAt = now;
  }

  if (params.extractedText !== undefined) {
    updatePayload.ocrText = params.extractedText?.trim() || null;
  }

  if (params.confidence !== undefined) {
    updatePayload.ocrConfidence = typeof params.confidence === "number" ? params.confidence : null;
  }

  if (params.extraction !== undefined) {
    updatePayload.ocrExtraction = params.extraction || null;
  }

  const expense = await Expense.findOneAndUpdate(
    {
      _id: params.expenseId,
      companyId: params.companyId,
      deletedAt: null,
    },
    { $set: updatePayload },
    { returnDocument: "after" }
  ).lean<Record<string, unknown> | null>();

  if (!expense) {
    return { success: false as const, message: "Expense not found" };
  }

  return { success: true as const, expense };
}

export async function applyDraftExpenseOcrSuggestion(params: {
  companyId: string;
  expenseId: string;
  updatedBy: string;
  suggestion: ExpenseDraftOcrSuggestion;
}) {
  await ConnectDb();

  if (
    !isValidObjectId(params.companyId) ||
    !isValidObjectId(params.expenseId) ||
    !isValidObjectId(params.updatedBy)
  ) {
    return { success: false as const, message: "Invalid OCR apply context" };
  }

  const existing = await Expense.findOne({
    _id: params.expenseId,
    companyId: params.companyId,
    deletedAt: null,
  }).lean<Record<string, unknown> | null>();

  if (!existing) {
    return { success: false as const, message: "Expense not found" };
  }

  if (existing.status !== "draft") {
    return { success: false as const, message: "Only draft expenses can be patched from OCR" };
  }

  const createdBy = toObjectIdString(existing.createdBy) || params.updatedBy;
  const resolvedSupplierId = !existing.supplierId
    ? await resolveSupplierId({
        createdBy,
        supplierName: params.suggestion.supplierName,
        supplierId: params.suggestion.supplierId,
      })
    : null;
  const resolvedCategoryId = !existing.categoryId
    ? await resolveCategoryId({
        companyId: params.companyId,
        categoryName: params.suggestion.categoryName,
        categoryId: params.suggestion.categoryId,
      })
    : null;

  const updatePayload: Record<string, unknown> = {
    updatedBy: toObjectId(params.updatedBy),
    ocrStatus: "completed",
    ocrError: null,
    ocrCompletedAt: new Date(),
    ocrText: params.suggestion.extractedText?.trim() || null,
    ocrConfidence: typeof params.suggestion.confidence === "number" ? params.suggestion.confidence : null,
    ocrExtraction: params.suggestion.extraction || null,
  };

  const suggestedAmountExclVatCents = toPositiveInteger(params.suggestion.amountExclVatCents);
  const suggestedVatRate = toVatRate(params.suggestion.vatRate);

  if ((Number(existing.amountInclVatCents) || 0) <= 0 && suggestedAmountExclVatCents !== null) {
    const vatRate = suggestedVatRate ?? 0;
    const vatAmountCents = computeVatAmountCents(suggestedAmountExclVatCents, vatRate);
    updatePayload.amountExclVatCents = suggestedAmountExclVatCents;
    updatePayload.vatRate = vatRate;
    updatePayload.vatAmountCents = vatAmountCents;
    updatePayload.amountInclVatCents = computeAmountInclVatCents(suggestedAmountExclVatCents, vatAmountCents);
  }

  if ((!existing.expenseDate || isAutoGeneratedDraftExpenseDate(existing)) && params.suggestion.expenseDate) {
    updatePayload.expenseDate = params.suggestion.expenseDate;
  }

  if ((!existing.dueDate || isAutoGeneratedDraftDueDate(existing)) && params.suggestion.dueDate) {
    updatePayload.dueDate = params.suggestion.dueDate;
  }

  if (!existing.supplierId && resolvedSupplierId) {
    updatePayload.supplierId = toObjectId(resolvedSupplierId);
  }

  if (!existing.categoryId && resolvedCategoryId) {
    updatePayload.categoryId = toObjectId(resolvedCategoryId);
  }

  if (isBlank(existing.supplierRef) && params.suggestion.supplierRef) {
    updatePayload.supplierRef = params.suggestion.supplierRef;
  }

  if (isBlank(existing.notes) && params.suggestion.notes) {
    updatePayload.notes = params.suggestion.notes;
  }

  if (
    (existing.expenseType === undefined || existing.expenseType === DEFAULT_EXPENSE_TYPE) &&
    params.suggestion.expenseType
  ) {
    updatePayload.expenseType = normalizeExpenseType(params.suggestion.expenseType);
  }

  const updated = await Expense.findOneAndUpdate(
    {
      _id: params.expenseId,
      companyId: params.companyId,
      status: "draft",
      deletedAt: null,
    },
    { $set: updatePayload },
    { returnDocument: "after", runValidators: true }
  ).lean<Record<string, unknown> | null>();

  if (!updated) {
    return { success: false as const, message: "Expense not found while applying OCR suggestion" };
  }

  await recordEntityFieldDiff({
    entityType: "expense",
    entityId: params.expenseId,
    companyId: params.companyId,
    performedBy: params.updatedBy,
    previous: {
      amountExclVatCents: existing.amountExclVatCents,
      vatRate: existing.vatRate,
      vatAmountCents: existing.vatAmountCents,
      amountInclVatCents: existing.amountInclVatCents,
      expenseDate: existing.expenseDate,
      dueDate: existing.dueDate,
      supplierId: existing.supplierId,
      categoryId: existing.categoryId,
      supplierRef: existing.supplierRef,
      notes: existing.notes,
      expenseType: existing.expenseType,
    },
    next: {
      amountExclVatCents: updated.amountExclVatCents,
      vatRate: updated.vatRate,
      vatAmountCents: updated.vatAmountCents,
      amountInclVatCents: updated.amountInclVatCents,
      expenseDate: updated.expenseDate,
      dueDate: updated.dueDate,
      supplierId: updated.supplierId,
      categoryId: updated.categoryId,
      supplierRef: updated.supplierRef,
      notes: updated.notes,
      expenseType: updated.expenseType,
    },
    source: "system",
  });

  return {
    success: true as const,
    expense: updated,
  };
}