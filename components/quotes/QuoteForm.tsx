'use client';

import { useEffect, useMemo, useRef, useState } from 'react';
import { useRouter } from 'next/navigation';

import { AlertTriangleIcon, ArrowLeftIcon, CalendarDaysIcon, NotebookTextIcon, PackageIcon, TagIcon, UserRoundIcon } from 'lucide-react';
import { toast } from 'sonner';

import ClientPicker from '@/components/quotes/ClientPicker';
import LineItemsBuilder from '@/components/quotes/LineItemsBuilder';
import type { QuoteLineItem } from '@/components/quotes/LineItemRow';
import QuoteTotals from '@/components/quotes/QuoteTotals';
import { useLocale } from '@/components/providers/locale-provider';
import { Button } from '@/components/ui/button';
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from '@/components/ui/dialog';
import ErrorMessage from '@/components/ui/ErrorMessage';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';

export interface QuoteFormData {
  _id: string;
  quoteNumber: string;
  clientId: string;
  date: string;
  subject?: string | null;
  lineItems: QuoteLineItem[];
  notes?: string | null;
  paymentTerms?: string | null;
  validityDays?: number;
  status: 'draft' | 'sent' | 'accepted' | 'refused' | 'rejected';
}

interface QuoteFormProps {
  mode: 'create' | 'edit';
  quote?: QuoteFormData;
  defaultClientId?: string;
}

export default function QuoteForm({ mode, quote, defaultClientId }: QuoteFormProps) {
  const router = useRouter();
  const { locale } = useLocale();

  const t = {
    en: {
      builder: 'Quote Builder',
      editPrefix: 'Edit',
      newQuote: 'New quote',
      quoteNumber: 'Quote number',
      autoGenerated: 'Auto-generated',
      backToQuotes: 'Back to quotes',
      backToDashboard: 'Dashboard',
      date: 'Date',
      client: 'Client',
      subject: 'Subject',
      subjectPlaceholder: 'e.g. Website, Logo, Construction...',
      lineItems: 'Products / Services',
      notes: 'Notes / Conditions',
      notesPlaceholder: 'Additional remarks or conditions...',
      paymentTerms: 'Payment terms',
      paymentTermsPlaceholder: 'e.g. Payment within 30 days',
      validityDays: 'Validity',
      validityDaysUnit: 'days',
      saving: 'Saving...',
      saveDraft: 'Save as Draft',
      saveAndSend: 'Save and Send',
      saveAndResend: 'Save & Resend',
      saveChanges: 'Save changes',
      clientRequired: 'Client is required',
      dateRequired: 'Date is required',
      lineItemsRequired: 'At least one line item is required',
      lineItemNameRequired: 'Each line item must have a name',
      saveFailed: 'Failed to save quote',
      saveAndSendSuccess: 'Quote saved and sent',
      saveDraftSuccess: 'Quote saved as draft',
      saveChangesSuccess: 'Quote updated',
      sendUnavailable: 'Quote saved as draft, but sending is not available yet.',
      sendFailed: 'Quote saved, but could not change status to sent.',
      unsavedTitle: 'Unsaved changes',
      unsavedDescription: 'You have unsaved changes that will be lost if you leave this page.',
      unsavedSaveDraft: 'Save as draft & leave',
      unsavedStay: 'Stay on page',
      unsavedLeave: 'Leave without saving',
      step1: 'Step 1',
      step2: 'Step 2',
      step3: 'Review',
      step4: 'Details',
    },
    fr: {
      builder: 'G\u00e9n\u00e9rateur de devis',
      editPrefix: 'Modifier',
      newQuote: 'Nouveau devis',
      quoteNumber: 'Num\u00e9ro de devis',
      autoGenerated: 'G\u00e9n\u00e9r\u00e9 automatiquement',
      backToQuotes: 'Retour aux devis',
      backToDashboard: 'Tableau de bord',
      date: 'Date',
      client: 'Client',
      subject: 'Objet',
      subjectPlaceholder: 'ex. Site web, Logo, Construction...',
      lineItems: 'Produits / Services',
      notes: 'Notes / Conditions',
      notesPlaceholder: 'Remarques ou conditions suppl\u00e9mentaires...',
      paymentTerms: 'Conditions de paiement',
      paymentTermsPlaceholder: 'ex. Paiement \u00e0 30 jours',
      validityDays: 'Dur\u00e9e de validit\u00e9',
      validityDaysUnit: 'jours',
      saving: 'Enregistrement...',
      saveDraft: 'Enregistrer en brouillon',
      saveAndSend: 'Enregistrer et envoyer',
      saveAndResend: 'Enregistrer et renvoyer',
      saveChanges: 'Enregistrer les modifications',
      clientRequired: 'Le client est requis',
      dateRequired: 'La date est requise',
      lineItemsRequired: 'Au moins une ligne est requise',
      lineItemNameRequired: 'Chaque ligne doit avoir un nom',
      saveFailed: "Impossible d'enregistrer le devis",
      saveAndSendSuccess: 'Devis enregistr\u00e9 et envoy\u00e9',
      saveDraftSuccess: 'Devis enregistr\u00e9 en brouillon',
      saveChangesSuccess: 'Devis mis \u00e0 jour',
      sendUnavailable: "Devis enregistr\u00e9 en brouillon, mais l'envoi n'est pas disponible.",
      sendFailed: "Devis enregistr\u00e9, mais impossible de passer le statut \u00e0 envoy\u00e9.",
      unsavedTitle: 'Modifications non enregistr\u00e9es',
      unsavedDescription: 'Vous avez des modifications non enregistr\u00e9es qui seront perdues si vous quittez.',
      unsavedSaveDraft: 'Enregistrer en brouillon et quitter',
      unsavedStay: 'Rester sur la page',
      unsavedLeave: 'Quitter sans enregistrer',
      step1: '\u00c9tape 1',
      step2: '\u00c9tape 2',
      step3: 'R\u00e9capitulatif',
      step4: 'D\u00e9tails',
    },
  }[locale];

  const [clientId, setClientId] = useState(quote?.clientId ?? defaultClientId ?? '');
  const [date, setDate] = useState(quote?.date ? quote.date.slice(0, 10) : new Date().toISOString().slice(0, 10));
  const [subject, setSubject] = useState(quote?.subject ?? '');
  const [lineItems, setLineItems] = useState<QuoteLineItem[]>(quote?.lineItems ?? []);
  const [notes, setNotes] = useState(quote?.notes ?? '');
  const [paymentTerms, setPaymentTerms] = useState(quote?.paymentTerms ?? '');
  const [validityDaysInput, setValidityDaysInput] = useState(String(quote?.validityDays ?? 30));
  const [quoteNumber, setQuoteNumber] = useState(quote?.quoteNumber ?? '');
  const [submitting, setSubmitting] = useState(false);
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [apiError, setApiError] = useState<string | null>(null);
  const [leaveDialogOpen, setLeaveDialogOpen] = useState(false);
  const [pendingNavUrl, setPendingNavUrl] = useState('/quotes');

  const savedRef = useRef(false);
  const isDirtyRef = useRef(false);
  const initialStateRef = useRef({
    clientId: quote?.clientId ?? defaultClientId ?? '',
    subject: quote?.subject ?? '',
    lineItems: JSON.stringify(quote?.lineItems ?? []),
    notes: quote?.notes ?? '',
    paymentTerms: quote?.paymentTerms ?? '',
    validityDaysInput: String(quote?.validityDays ?? 30),
  });

  function normalizeValidityDays(value: string): number {
    const parsed = Number(value);
    if (!Number.isFinite(parsed)) {
      return 30;
    }
    return Math.min(365, Math.max(1, Math.round(parsed)));
  }

  useEffect(() => {
    if (mode !== 'create') {
      return;
    }

    let cancelled = false;

    async function fetchQuoteNumber() {
      try {
        const response = await fetch('/api/quotes/next-number');
        const payload = (await response.json()) as { quoteNumber?: string };
        if (!cancelled) {
          setQuoteNumber(payload.quoteNumber || `DEV-${new Date().getFullYear()}-001`);
        }
      } catch {
        if (!cancelled) {
          setQuoteNumber(`DEV-${new Date().getFullYear()}-001`);
        }
      }
    }

    fetchQuoteNumber();

    return () => {
      cancelled = true;
    };
  }, [mode]);

  useEffect(() => {
    if (!quote) {
      return;
    }

    setClientId(quote.clientId);
    setDate(quote.date.slice(0, 10));
    setSubject(quote.subject ?? '');
    setLineItems(quote.lineItems);
    setNotes(quote.notes ?? '');
    setPaymentTerms(quote.paymentTerms ?? '');
    setValidityDaysInput(String(quote.validityDays ?? 30));
    setQuoteNumber(quote.quoteNumber);
    // Reset the dirty baseline when quote data loads
    initialStateRef.current = {
      clientId: quote.clientId,
      subject: quote.subject ?? '',
      lineItems: JSON.stringify(quote.lineItems),
      notes: quote.notes ?? '',
      paymentTerms: quote.paymentTerms ?? '',
      validityDaysInput: String(quote.validityDays ?? 30),
    };
  }, [quote]);

  const title = useMemo(() => {
    if (mode === 'edit') {
      return `${t.editPrefix} ${quoteNumber}`;
    }

    return t.newQuote;
  }, [mode, quoteNumber, t.editPrefix, t.newQuote]);

  const showResendAction =
    mode === 'edit' &&
    (quote?.status === 'rejected' || quote?.status === 'sent');
  const hasSecondaryAction = mode === 'create' || showResendAction;

  const isDirty = useMemo(() => {
    const init = initialStateRef.current;
    if (clientId !== init.clientId) return true;
    if (subject !== init.subject) return true;
    if (notes !== init.notes) return true;
    if (paymentTerms !== init.paymentTerms) return true;
    if (validityDaysInput !== init.validityDaysInput) return true;
    if (JSON.stringify(lineItems) !== init.lineItems) return true;
    return false;
  }, [clientId, subject, lineItems, notes, paymentTerms, validityDaysInput]);

  // Keep isDirtyRef in sync so event listeners always read latest value
  useEffect(() => {
    isDirtyRef.current = isDirty;
  }, [isDirty]);

  // Block browser tab close / refresh when there are unsaved changes
  useEffect(() => {
    function handleBeforeUnload(e: BeforeUnloadEvent) {
      if (!isDirtyRef.current || savedRef.current) return;
      e.preventDefault();
      e.returnValue = '';
    }
    window.addEventListener('beforeunload', handleBeforeUnload);
    return () => window.removeEventListener('beforeunload', handleBeforeUnload);
  }, []);

  // Intercept the browser back button
  useEffect(() => {
    window.history.pushState({ __quoteGuard: true }, '');

    function handlePopState() {
      if (isDirtyRef.current && !savedRef.current) {
        // Re-push the guard entry so the URL stays the same
        window.history.pushState({ __quoteGuard: true }, '');
        setPendingNavUrl('/quotes');
        setLeaveDialogOpen(true);
      }
    }

    window.addEventListener('popstate', handlePopState);
    return () => window.removeEventListener('popstate', handlePopState);
  }, []);

  function requestNavigate(url: string) {
    if (isDirty) {
      setPendingNavUrl(url);
      setLeaveDialogOpen(true);
    } else {
      savedRef.current = true;
      router.push(url);
    }
  }

  function validate() {
    const nextErrors: Record<string, string> = {};

    if (!clientId) {
      nextErrors.clientId = t.clientRequired;
    }

    if (!date) {
      nextErrors.date = t.dateRequired;
    }

    if (lineItems.length === 0) {
      nextErrors.lineItems = t.lineItemsRequired;
    }

    for (let index = 0; index < lineItems.length; index += 1) {
      const row = lineItems[index];
      if (!row.name.trim()) {
        nextErrors.lineItems = t.lineItemNameRequired;
        break;
      }
    }

    setErrors(nextErrors);
    return Object.keys(nextErrors).length === 0;
  }

  async function saveQuote(sendAfterSave: boolean) {
    if (!validate()) {
      return;
    }

    setApiError(null);
    setSubmitting(true);

    try {
      const validityDays = normalizeValidityDays(validityDaysInput);
      const payload = {
        clientId,
        date,
        subject: subject.trim() || null,
        lineItems,
        notes: notes.trim() || null,
        paymentTerms: paymentTerms.trim() || null,
        validityDays,
      };

      const isCreate = mode === 'create';
      const endpoint = isCreate ? '/api/quotes' : `/api/quotes/${quote?._id}`;
      const method = isCreate ? 'POST' : 'PATCH';

      const response = await fetch(endpoint, {
        method,
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      });

      const result = (await response.json()) as {
        success?: boolean;
        message?: string;
        data?: { _id: string };
      };

      if (!response.ok || !result.success) {
        throw new Error(result.message || t.saveFailed);
      }

      const quoteId = result.data?._id || quote?._id;

      if (sendAfterSave && quoteId) {
        toast.success(t.saveAndSendSuccess);
        savedRef.current = true;
        setLeaveDialogOpen(false);
        router.push(`/quotes/${quoteId}?send=1`);
        return;
      }

      const successMessage = mode === 'edit' ? t.saveChangesSuccess : t.saveDraftSuccess;

      toast.success(successMessage);
      savedRef.current = true;
      setLeaveDialogOpen(false);
      router.push('/quotes');
    } catch (saveError) {
      setApiError(saveError instanceof Error ? saveError.message : t.saveFailed);
    } finally {
      setSubmitting(false);
    }
  }

  return (
    <section data-tour-quote-form className="space-y-4 pb-24 lg:pb-6">
      <header className="rounded-xl border border-border/70 bg-linear-to-b from-background to-secondary/30 p-4 sm:p-5">
        <div className="mb-4 flex items-start justify-between gap-3">
          <div className="space-y-1">
            <button
              type="button"
              className="mb-1 inline-flex items-center gap-1.5 text-xs text-muted-foreground hover:text-foreground"
              onClick={() => requestNavigate('/quotes')}
            >
              <ArrowLeftIcon className="size-3" />
              {t.backToQuotes}
            </button>
            <h1 className="font-heading text-2xl font-semibold tracking-tight sm:text-3xl">{title}</h1>
          </div>
        </div>

        <div className="grid gap-3 sm:grid-cols-2">
          <div className="space-y-1.5 rounded-lg border border-border/70 bg-background/80 p-3">
            <Label htmlFor="quote-number">{t.quoteNumber}</Label>
            <Input id="quote-number" value={quoteNumber} readOnly className="bg-muted/40" />
            <p className="text-xs text-muted-foreground">{t.autoGenerated}</p>
          </div>
          <div className="space-y-1.5 rounded-lg border border-border/70 bg-background/80 p-3">
            <Label htmlFor="quote-date">{t.date}</Label>
            <div className="relative">
              <CalendarDaysIcon className="pointer-events-none absolute right-3 top-1/2 size-4 -translate-y-1/2 text-muted-foreground" />
              <Input
                id="quote-date"
                type="date"
                value={date}
                onChange={(event) => setDate(event.target.value)}
                className="pr-9"
              />
            </div>
            {errors.date ? <p className="text-xs text-destructive">{errors.date}</p> : null}
          </div>
        </div>

        <div className="mt-3 space-y-1.5 rounded-lg border border-border/70 bg-background/80 p-3">
          <Label htmlFor="quote-subject" className="inline-flex items-center gap-2">
            <TagIcon className="size-3.5 text-muted-foreground" />
            {t.subject}
          </Label>
          <Input
            id="quote-subject"
            data-tour-quote-subject
            value={subject}
            onChange={(event) => setSubject(event.target.value)}
            placeholder={t.subjectPlaceholder}
            maxLength={200}
          />
        </div>
      </header>

      {apiError ? <ErrorMessage message={apiError} /> : null}

      <div className="grid gap-4 lg:grid-cols-[1.5fr_1fr]">
        <div className="space-y-4">
          <section data-tour-quote-client-step className="rounded-xl border border-border/70 bg-card p-4 shadow-sm">
            <h2 className="mb-3 inline-flex items-center gap-2 font-heading text-base font-semibold">
              <span className="flex size-6 items-center justify-center rounded-full bg-primary text-[11px] font-bold text-primary-foreground">{clientId ? '✓' : '1'}</span>
              <UserRoundIcon className="size-4 text-muted-foreground" />
              {t.client}
              <span className="text-xs font-normal text-muted-foreground">— {t.step1}</span>
            </h2>
            <ClientPicker value={clientId} onChange={setClientId} onClientSelected={() => undefined} />
            {errors.clientId ? <p className="mt-2 text-xs text-destructive">{errors.clientId}</p> : null}
          </section>

          <section data-tour-quote-items-step className="rounded-xl border border-border/70 bg-card p-4 shadow-sm">
            <h2 className="mb-3 inline-flex items-center gap-2 font-heading text-base font-semibold">
              <span className="flex size-6 items-center justify-center rounded-full bg-primary text-[11px] font-bold text-primary-foreground">{lineItems.length > 0 ? '✓' : '2'}</span>
              <PackageIcon className="size-4 text-muted-foreground" />
              {t.lineItems}
              <span className="text-xs font-normal text-muted-foreground">— {t.step2}</span>
            </h2>
            <LineItemsBuilder lineItems={lineItems} onChange={setLineItems} />
            {errors.lineItems ? <p className="mt-2 text-xs text-destructive">{errors.lineItems}</p> : null}
          </section>
        </div>

        <aside className="space-y-4 lg:sticky lg:top-20 lg:self-start">

          {/* ── Sticky save bar ─ compact on mobile, card on desktop ─── */}
          <div
            data-tour-quote-save-actions
            className="fixed inset-x-3 bottom-2 z-30 rounded-2xl border border-border/70 bg-background/95 px-3 pt-3 shadow-[0_14px_36px_-18px_rgba(0,0,0,0.4)] backdrop-blur lg:static lg:rounded-xl lg:bg-background/95 lg:p-4 lg:shadow-sm"
            style={{ paddingBottom: 'max(env(safe-area-inset-bottom, 0px), 12px)' }}
          >
            <div className={hasSecondaryAction ? 'grid grid-cols-2 gap-2 lg:grid-cols-1' : 'grid grid-cols-1 gap-2'}>
              {mode === 'edit' ? (
                <>
                  {showResendAction ? (
                    <Button type="button" className="h-11 w-full rounded-xl text-sm font-semibold lg:h-11" disabled={submitting} onClick={() => saveQuote(true)}>
                      {submitting ? t.saving : t.saveAndResend}
                    </Button>
                  ) : null}
                  <Button type="button" variant={showResendAction ? 'outline' : 'default'} className="h-11 w-full rounded-xl text-sm font-semibold lg:h-11" disabled={submitting} onClick={() => saveQuote(false)}>
                    {submitting ? t.saving : t.saveChanges}
                  </Button>
                </>
              ) : (
                <>
                  <Button type="button" className="h-11 w-full rounded-xl text-sm font-semibold lg:h-11" disabled={submitting} onClick={() => saveQuote(true)}>
                    {submitting ? t.saving : t.saveAndSend}
                  </Button>
                  <Button type="button" variant="outline" className="h-11 w-full rounded-xl text-sm font-semibold lg:h-11" disabled={submitting} onClick={() => saveQuote(false)}>
                    {submitting ? t.saving : t.saveDraft}
                  </Button>
                </>
              )}
            </div>
          </div>

          <div data-tour-quote-totals-step>
            <h2 className="mb-3 inline-flex items-center gap-2 font-heading text-base font-semibold">
              <span className="flex size-6 items-center justify-center rounded-full bg-primary text-[11px] font-bold text-primary-foreground">3</span>
              {t.step3}
            </h2>
            <QuoteTotals lineItems={lineItems} />
          </div>

          <section className="rounded-xl border border-border/70 bg-card p-4 shadow-sm space-y-4">
            <h2 className="inline-flex items-center gap-2 font-heading text-base font-semibold">
              <span className="flex size-6 items-center justify-center rounded-full bg-primary text-[11px] font-bold text-primary-foreground">4</span>
              {t.step4}
            </h2>
            <div className="grid grid-cols-2 gap-3">
              <div className="space-y-1.5">
                <Label htmlFor="quote-payment-terms">
                  {t.paymentTerms}
                </Label>
                <Input
                  id="quote-payment-terms"
                  value={paymentTerms}
                  onChange={(event) => setPaymentTerms(event.target.value)}
                  placeholder={t.paymentTermsPlaceholder}
                />
              </div>

              <div className="space-y-1.5">
                <Label htmlFor="quote-validity-days">
                  {t.validityDays}
                </Label>
                <div className="flex items-center gap-2">
                  <Input
                    id="quote-validity-days"
                    type="number"
                    min={1}
                    max={365}
                    value={validityDaysInput}
                    onChange={(event) => setValidityDaysInput(event.target.value)}
                    onBlur={() => setValidityDaysInput(String(normalizeValidityDays(validityDaysInput)))}
                    className="w-full"
                  />
                  <span className="text-sm text-muted-foreground">{t.validityDaysUnit}</span>
                </div>
              </div>
            </div>

            <div className="space-y-1.5">
              <Label htmlFor="quote-notes" className="inline-flex items-center gap-2">
                <NotebookTextIcon className="size-4 text-muted-foreground" />
                {t.notes}
              </Label>
              <textarea
                id="quote-notes"
                className="mt-1 min-h-28 w-full rounded-lg border border-input bg-background px-3 py-2 text-sm outline-none transition-colors focus-visible:border-ring focus-visible:ring-3 focus-visible:ring-ring/50"
                placeholder={t.notesPlaceholder}
                value={notes}
                onChange={(event) => setNotes(event.target.value)}
              />
            </div>
          </section>
        </aside>
      </div>

      <Dialog open={leaveDialogOpen} onOpenChange={setLeaveDialogOpen}>
        <DialogContent className="sm:max-w-sm">
          <DialogHeader>
            <DialogTitle className="flex items-center gap-2">
              <AlertTriangleIcon className="size-5 text-amber-500" />
              {t.unsavedTitle}
            </DialogTitle>
            <DialogDescription>{t.unsavedDescription}</DialogDescription>
          </DialogHeader>
          <DialogFooter className="flex flex-col gap-2">
            <Button
              type="button"
              className="w-full"
              disabled={submitting}
              onClick={() => {
                setLeaveDialogOpen(false);
                saveQuote(false);
              }}
            >
              {submitting ? t.saving : t.unsavedSaveDraft}
            </Button>
            <Button
              type="button"
              variant="outline"
              className="w-full"
              onClick={() => setLeaveDialogOpen(false)}
            >
              {t.unsavedStay}
            </Button>
            <Button
              type="button"
              variant="ghost"
              className="w-full text-destructive hover:text-destructive"
              onClick={() => {
                savedRef.current = true;
                setLeaveDialogOpen(false);
                router.push(pendingNavUrl);
              }}
            >
              {t.unsavedLeave}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </section>
  );
}
