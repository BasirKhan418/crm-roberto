'use client';

import { useEffect, useMemo, useState } from 'react';
import Link from 'next/link';
import { useRouter } from 'next/navigation';

import { ArrowLeftIcon, CalendarDaysIcon, FileTextIcon, NotebookTextIcon, UserRoundIcon } from 'lucide-react';
import { toast } from 'sonner';

import ClientPicker from '@/components/quotes/ClientPicker';
import LineItemsBuilder from '@/components/quotes/LineItemsBuilder';
import type { QuoteLineItem } from '@/components/quotes/LineItemRow';
import QuoteTotals from '@/components/quotes/QuoteTotals';
import { useLocale } from '@/components/providers/locale-provider';
import { Button } from '@/components/ui/button';
import ErrorMessage from '@/components/ui/ErrorMessage';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';

export interface QuoteFormData {
  _id: string;
  quoteNumber: string;
  clientId: string;
  date: string;
  lineItems: QuoteLineItem[];
  notes?: string | null;
  paymentTerms?: string | null;
  validityDays?: number;
  status: 'draft' | 'sent' | 'accepted' | 'refused';
}

interface QuoteFormProps {
  mode: 'create' | 'edit';
  quote?: QuoteFormData;
}

export default function QuoteForm({ mode, quote }: QuoteFormProps) {
  const router = useRouter();
  const { locale } = useLocale();

  const t = {
    en: {
      builder: 'Quote Builder',
      editPrefix: 'Edit',
      newQuote: 'New quote',
      quoteNumber: 'Quote number',
      autoGenerated: 'Auto-generated',
      backToQuotes: 'Back to quotes',
      date: 'Date',
      client: 'Client',
      lineItems: 'Line items',
      notes: 'Notes / Conditions',
      notesPlaceholder: 'Additional remarks or conditions...',
      paymentTerms: 'Payment terms',
      paymentTermsPlaceholder: 'e.g. Payment within 30 days',
      validityDays: 'Validity',
      validityDaysUnit: 'days',
      saving: 'Saving...',
      saveDraft: 'Save as Draft',
      saveAndSend: 'Save and Send',
      saveChanges: 'Save changes',
      clientRequired: 'Client is required',
      dateRequired: 'Date is required',
      lineItemsRequired: 'At least one line item is required',
      lineItemNameRequired: 'Each line item must have a name',
      saveFailed: 'Failed to save quote',
      saveAndSendSuccess: 'Quote saved and sent',
      saveDraftSuccess: 'Quote saved as draft',
      saveChangesSuccess: 'Quote updated',
      sendUnavailable: 'Quote saved as draft, but sending is not available yet.',
      sendFailed: 'Quote saved, but could not change status to sent.',
    },
    fr: {
      builder: 'Generateur de devis',
      editPrefix: 'Modifier',
      newQuote: 'Nouveau devis',
      quoteNumber: 'Numero de devis',
      autoGenerated: 'Genere automatiquement',
      backToQuotes: 'Retour aux devis',
      date: 'Date',
      client: 'Client',
      lineItems: 'Lignes',
      notes: 'Notes / Conditions',
      notesPlaceholder: 'Remarques ou conditions supplementaires...',
      paymentTerms: 'Conditions de paiement',
      paymentTermsPlaceholder: 'ex. Paiement a 30 jours',
      validityDays: 'Duree de validite',
      validityDaysUnit: 'jours',
      saving: 'Enregistrement...',
      saveDraft: 'Enregistrer en brouillon',
      saveAndSend: 'Enregistrer et envoyer',
      saveChanges: 'Enregistrer les modifications',
      clientRequired: 'Le client est requis',
      dateRequired: 'La date est requise',
      lineItemsRequired: 'Au moins une ligne est requise',
      lineItemNameRequired: 'Chaque ligne doit avoir un nom',
      saveFailed: 'Impossible d enregistrer le devis',
      saveAndSendSuccess: 'Devis enregistre et envoye',
      saveDraftSuccess: 'Devis enregistre en brouillon',
      saveChangesSuccess: 'Devis mis a jour',
      sendUnavailable: 'Devis enregistre en brouillon, mais l envoi n est pas disponible.',
      sendFailed: 'Devis enregistre, mais impossible de passer le statut a envoye.',
    },
  }[locale];

  const [clientId, setClientId] = useState(quote?.clientId ?? '');
  const [date, setDate] = useState(quote?.date ? quote.date.slice(0, 10) : new Date().toISOString().slice(0, 10));
  const [lineItems, setLineItems] = useState<QuoteLineItem[]>(quote?.lineItems ?? []);
  const [notes, setNotes] = useState(quote?.notes ?? '');
  const [paymentTerms, setPaymentTerms] = useState(quote?.paymentTerms ?? '');
  const [validityDaysInput, setValidityDaysInput] = useState(String(quote?.validityDays ?? 30));
  const [quoteNumber, setQuoteNumber] = useState(quote?.quoteNumber ?? '');
  const [submitting, setSubmitting] = useState(false);
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [apiError, setApiError] = useState<string | null>(null);

  function normalizeValidityDays(value: string): number {
    const parsed = Number(value);
    if (!Number.isFinite(parsed)) {
      return 30;
    }
    return Math.min(365, Math.max(1, Math.round(parsed)));
  }

  useEffect(() => {
    if (mode !== 'create') {
      return;
    }

    let cancelled = false;

    async function fetchQuoteNumber() {
      try {
        const response = await fetch('/api/quotes/next-number');
        const payload = (await response.json()) as { quoteNumber?: string };
        if (!cancelled) {
          setQuoteNumber(payload.quoteNumber || `DEV-${new Date().getFullYear()}-001`);
        }
      } catch {
        if (!cancelled) {
          setQuoteNumber(`DEV-${new Date().getFullYear()}-001`);
        }
      }
    }

    fetchQuoteNumber();

    return () => {
      cancelled = true;
    };
  }, [mode]);

  useEffect(() => {
    if (!quote) {
      return;
    }

    setClientId(quote.clientId);
    setDate(quote.date.slice(0, 10));
    setLineItems(quote.lineItems);
    setNotes(quote.notes ?? '');
    setPaymentTerms(quote.paymentTerms ?? '');
    setValidityDaysInput(String(quote.validityDays ?? 30));
    setQuoteNumber(quote.quoteNumber);
  }, [quote]);

  const title = useMemo(() => {
    if (mode === 'edit') {
      return `${t.editPrefix} ${quoteNumber}`;
    }

    return t.newQuote;
  }, [mode, quoteNumber, t.editPrefix, t.newQuote]);

  function validate() {
    const nextErrors: Record<string, string> = {};

    if (!clientId) {
      nextErrors.clientId = t.clientRequired;
    }

    if (!date) {
      nextErrors.date = t.dateRequired;
    }

    if (lineItems.length === 0) {
      nextErrors.lineItems = t.lineItemsRequired;
    }

    for (let index = 0; index < lineItems.length; index += 1) {
      const row = lineItems[index];
      if (!row.name.trim()) {
        nextErrors.lineItems = t.lineItemNameRequired;
        break;
      }
    }

    setErrors(nextErrors);
    return Object.keys(nextErrors).length === 0;
  }

  async function saveQuote(sendAfterSave: boolean) {
    if (!validate()) {
      return;
    }

    setApiError(null);
    setSubmitting(true);

    try {
      const validityDays = normalizeValidityDays(validityDaysInput);
      const payload = {
        clientId,
        date,
        lineItems,
        notes: notes.trim() || null,
        paymentTerms: paymentTerms.trim() || null,
        validityDays,
      };

      const isCreate = mode === 'create';
      const endpoint = isCreate ? '/api/quotes' : `/api/quotes/${quote?._id}`;
      const method = isCreate ? 'POST' : 'PATCH';

      const response = await fetch(endpoint, {
        method,
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      });

      const result = (await response.json()) as {
        success?: boolean;
        message?: string;
        data?: { _id: string };
      };

      if (!response.ok || !result.success) {
        throw new Error(result.message || t.saveFailed);
      }

      let sendSucceeded = false;

      if (sendAfterSave) {
        const quoteId = result.data?._id || quote?._id;
        if (!quoteId) {
          throw new Error(t.sendFailed);
        }

        const sendResponse = await fetch(`/api/quotes/${quoteId}/status`, {
          method: 'PATCH',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ to: 'sent' }),
        });

        if (sendResponse.ok) {
          sendSucceeded = true;
        } else {
          const sendPayload = (await sendResponse.json().catch(() => null)) as { message?: string } | null;
          throw new Error(sendPayload?.message || t.sendUnavailable);
        }
      }

      const successMessage = mode === 'edit'
        ? t.saveChangesSuccess
        : sendAfterSave
          ? (sendSucceeded ? t.saveAndSendSuccess : t.saveDraftSuccess)
          : t.saveDraftSuccess;

      toast.success(successMessage);
      router.push('/quotes');
    } catch (saveError) {
      setApiError(saveError instanceof Error ? saveError.message : t.saveFailed);
    } finally {
      setSubmitting(false);
    }
  }

  return (
    <section className="space-y-5 pb-28 xl:pb-6">
      <header className="rounded-xl border border-border/70 bg-linear-to-b from-background to-secondary/30 p-4 sm:p-5">
        <div className="mb-4 flex items-start justify-between gap-3">
          <div className="space-y-1">
            <Button type="button" variant="ghost" size="sm" className="mb-1 h-7 px-0 text-muted-foreground hover:text-foreground" asChild>
              <Link href="/quotes">
                <ArrowLeftIcon className="size-3.5" />
                {t.backToQuotes}
              </Link>
            </Button>
            <h1 className="font-heading text-2xl font-semibold tracking-tight sm:text-3xl">{title}</h1>
          </div>
        </div>

        <div className="grid gap-3 sm:grid-cols-2">
          <div className="space-y-1.5 rounded-lg border border-border/70 bg-background/80 p-3">
            <Label htmlFor="quote-number">{t.quoteNumber}</Label>
            <Input id="quote-number" value={quoteNumber} readOnly className="bg-muted/40" />
            <p className="text-xs text-muted-foreground">{t.autoGenerated}</p>
          </div>
          <div className="space-y-1.5 rounded-lg border border-border/70 bg-background/80 p-3">
            <Label htmlFor="quote-date">{t.date}</Label>
            <div className="relative">
              <CalendarDaysIcon className="pointer-events-none absolute right-3 top-1/2 size-4 -translate-y-1/2 text-muted-foreground" />
              <Input
                id="quote-date"
                type="date"
                value={date}
                onChange={(event) => setDate(event.target.value)}
                className="pr-9"
              />
            </div>
            {errors.date ? <p className="text-xs text-destructive">{errors.date}</p> : null}
          </div>
        </div>
      </header>

      {apiError ? <ErrorMessage message={apiError} /> : null}

      <div className="grid gap-4 xl:grid-cols-[1.5fr_1fr]">
        <div className="space-y-4">
          <section className="rounded-xl border border-border/70 bg-card p-4 shadow-sm">
            <h2 className="mb-3 inline-flex items-center gap-2 font-heading text-base font-semibold">
              <UserRoundIcon className="size-4 text-muted-foreground" />
              {t.client}
            </h2>
            <ClientPicker value={clientId} onChange={setClientId} onClientSelected={() => undefined} />
            {errors.clientId ? <p className="mt-2 text-xs text-destructive">{errors.clientId}</p> : null}
          </section>

          <section className="rounded-xl border border-border/70 bg-card p-4 shadow-sm">
            <h2 className="mb-3 inline-flex items-center gap-2 font-heading text-base font-semibold">
              <FileTextIcon className="size-4 text-muted-foreground" />
              {t.lineItems}
            </h2>
            <LineItemsBuilder lineItems={lineItems} onChange={setLineItems} />
            {errors.lineItems ? <p className="mt-2 text-xs text-destructive">{errors.lineItems}</p> : null}
          </section>
        </div>

        <aside className="space-y-4 xl:sticky xl:top-20 xl:self-start">
          <QuoteTotals lineItems={lineItems} />

          <section className="rounded-xl border border-border/70 bg-card p-4 shadow-sm space-y-4">
            <div className="space-y-1.5">
              <Label htmlFor="quote-payment-terms">
                {t.paymentTerms}
              </Label>
              <Input
                id="quote-payment-terms"
                value={paymentTerms}
                onChange={(event) => setPaymentTerms(event.target.value)}
                placeholder={t.paymentTermsPlaceholder}
              />
            </div>

            <div className="space-y-1.5">
              <Label htmlFor="quote-validity-days">
                {t.validityDays}
              </Label>
              <div className="flex items-center gap-2">
                <Input
                  id="quote-validity-days"
                  type="number"
                  min={1}
                  max={365}
                  value={validityDaysInput}
                  onChange={(event) => setValidityDaysInput(event.target.value)}
                  onBlur={() => setValidityDaysInput(String(normalizeValidityDays(validityDaysInput)))}
                  className="w-24"
                />
                <span className="text-sm text-muted-foreground">{t.validityDaysUnit}</span>
              </div>
            </div>

            <div className="space-y-1.5">
              <Label htmlFor="quote-notes" className="inline-flex items-center gap-2">
                <NotebookTextIcon className="size-4 text-muted-foreground" />
                {t.notes}
              </Label>
              <textarea
                id="quote-notes"
                className="mt-1 min-h-28 w-full rounded-lg border border-input bg-background px-3 py-2 text-sm outline-none transition-colors focus-visible:border-ring focus-visible:ring-3 focus-visible:ring-ring/50"
                placeholder={t.notesPlaceholder}
                value={notes}
                onChange={(event) => setNotes(event.target.value)}
              />
            </div>
          </section>

          <div className="fixed inset-x-0 bottom-0 z-30 border-t border-border/70 bg-background/95 px-3 py-3 pb-[max(0.75rem,env(safe-area-inset-bottom))] shadow-[0_-8px_24px_-16px_rgba(0,0,0,0.45)] backdrop-blur xl:static xl:rounded-xl xl:border xl:bg-background/95 xl:p-3 xl:shadow-sm">
            <div className="flex flex-col gap-2 sm:flex-row sm:justify-end">
              {mode === 'edit' ? (
                <Button type="button" className="h-11 sm:min-w-44" disabled={submitting} onClick={() => saveQuote(false)}>
                  {submitting ? t.saving : t.saveChanges}
                </Button>
              ) : (
                <>
                  <Button type="button" variant="outline" className="h-11 sm:min-w-36" disabled={submitting} onClick={() => saveQuote(false)}>
                    {submitting ? t.saving : t.saveDraft}
                  </Button>
                  <Button type="button" className="h-11 sm:min-w-36" disabled={submitting} onClick={() => saveQuote(true)}>
                    {submitting ? t.saving : t.saveAndSend}
                  </Button>
                </>
              )}
            </div>
          </div>
        </aside>
      </div>
    </section>
  );
}
