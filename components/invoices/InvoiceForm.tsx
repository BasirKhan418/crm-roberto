'use client';

import { useEffect, useState } from 'react';
import { useRouter } from 'next/navigation';

import { CalendarDaysIcon, FileTextIcon, NotebookTextIcon, UserRoundIcon } from 'lucide-react';
import { toast } from 'sonner';

import ClientPicker from '@/components/quotes/ClientPicker';
import LineItemsBuilder from '@/components/quotes/LineItemsBuilder';
import type { QuoteLineItem } from '@/components/quotes/LineItemRow';
import QuoteTotals from '@/components/quotes/QuoteTotals';
import { useLocale } from '@/components/providers/locale-provider';
import { formatInvoiceDisplayNumber } from '@/lib/i18n/messages';
import { Button } from '@/components/ui/button';
import ErrorMessage from '@/components/ui/ErrorMessage';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';

interface InvoiceFormProps {
  defaultClientId?: string;
  defaultQuoteId?: string;
  defaultDueDate?: string;
}

export default function InvoiceForm({ defaultClientId, defaultQuoteId, defaultDueDate }: InvoiceFormProps) {
  const router = useRouter();
  const { locale } = useLocale();

  const t = {
    en: {
      title: 'New invoice',
      subtitle: 'Create an invoice from line items or convert a signed quote.',
      backToInvoices: 'Back to invoices',
      invoiceNumber: 'Invoice number',
      autoGenerated: 'Auto-generated',
      date: 'Date',
      dueDate: 'Due date',
      client: 'Client',
      lineItems: 'Products / Services',
      notes: 'Notes',
      notesPlaceholder: 'Add payment or legal notes...',
      createInvoice: 'Create invoice',
      creating: 'Creating...',
      createSuccess: 'Invoice created successfully',
      createFailed: 'Failed to create invoice',
      clientRequired: 'Client is required',
      dateRequired: 'Date is required',
      dueDateRequired: 'Due date is mandatory',
      dueDateInvalid: 'Due date must be after invoice date',
      lineItemsRequired: 'At least one line item is required',
      lineItemNameRequired: 'Each line item must have a name',
      fromQuoteTitle: 'Convert signed quote',
      fromQuoteText: 'This invoice will be created directly from the selected quote.',
      quoteIdInvalid: 'Missing quote id',
      step1: 'Step 1',
      step2: 'Step 2',
      step3: 'Review',
      step4: 'Details',
    },
    fr: {
      title: 'Nouvelle facture',
      subtitle: 'Cr\u00e9ez une facture depuis des lignes ou convertissez un devis sign\u00e9.',
      backToInvoices: 'Retour aux factures',
      invoiceNumber: 'Num\u00e9ro de facture',
      autoGenerated: 'G\u00e9n\u00e9r\u00e9 automatiquement',
      date: 'Date',
      dueDate: '\u00c9ch\u00e9ance',
      client: 'Client',
      lineItems: 'Produits / Services',
      notes: 'Notes',
      notesPlaceholder: 'Ajoutez des notes de paiement ou l\u00e9gales...',
      createInvoice: 'Cr\u00e9er la facture',
      creating: 'Cr\u00e9ation...',
      createSuccess: 'Facture cr\u00e9\u00e9e avec succ\u00e8s',
      createFailed: 'Impossible de cr\u00e9er la facture',
      clientRequired: 'Le client est requis',
      dateRequired: 'La date est requise',
      dueDateRequired: "L'echeance est obligatoire",
      dueDateInvalid: "L'\u00e9ch\u00e9ance doit \u00eatre post\u00e9rieure \u00e0 la date de facture",
      lineItemsRequired: 'Au moins une ligne est requise',
      lineItemNameRequired: 'Chaque ligne doit avoir un nom',
      fromQuoteTitle: 'Convertir un devis sign\u00e9',
      fromQuoteText: 'Cette facture sera cr\u00e9\u00e9e directement depuis le devis s\u00e9lectionn\u00e9.',
      quoteIdInvalid: 'Identifiant du devis manquant',
      step1: '\u00c9tape 1',
      step2: '\u00c9tape 2',
      step3: 'R\u00e9capitulatif',
      step4: 'D\u00e9tails',
    },
  }[locale];

  const [invoiceNumber, setInvoiceNumber] = useState('');
  const [clientId, setClientId] = useState(defaultClientId ?? '');
  const [date, setDate] = useState(new Date().toISOString().slice(0, 10));
  const [dueDate, setDueDate] = useState(defaultDueDate ?? '');
  const [lineItems, setLineItems] = useState<QuoteLineItem[]>([]);
  const [notes, setNotes] = useState('');
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [apiError, setApiError] = useState<string | null>(null);
  const [submitting, setSubmitting] = useState(false);

  const convertFromQuote = Boolean(defaultQuoteId);

  useEffect(() => {
    let cancelled = false;

    async function fetchNextNumber() {
      try {
        const response = await fetch('/api/invoices/next-number');
        const payload = (await response.json()) as { invoiceNumber?: string };
        if (!cancelled) {
          setInvoiceNumber(payload.invoiceNumber || `INV-${new Date().getFullYear()}-001`);
        }
      } catch {
        if (!cancelled) {
          setInvoiceNumber(`INV-${new Date().getFullYear()}-001`);
        }
      }
    }

    fetchNextNumber();
    return () => {
      cancelled = true;
    };
  }, []);

  function validate() {
    const nextErrors: Record<string, string> = {};

    if (!dueDate) {
      nextErrors.dueDate = t.dueDateRequired;
    }

    if (convertFromQuote) {
      if (!defaultQuoteId) {
        nextErrors.quoteId = t.quoteIdInvalid;
      }

      setErrors(nextErrors);
      return Object.keys(nextErrors).length === 0;
    }

    if (!clientId) {
      nextErrors.clientId = t.clientRequired;
    }

    if (!date) {
      nextErrors.date = t.dateRequired;
    }

    if (dueDate && date && new Date(dueDate).getTime() < new Date(date).getTime()) {
      nextErrors.dueDate = t.dueDateInvalid;
    }

    if (lineItems.length === 0) {
      nextErrors.lineItems = t.lineItemsRequired;
    }

    for (let index = 0; index < lineItems.length; index += 1) {
      if (!lineItems[index].name.trim()) {
        nextErrors.lineItems = t.lineItemNameRequired;
        break;
      }
    }

    setErrors(nextErrors);
    return Object.keys(nextErrors).length === 0;
  }

  async function handleSubmit() {
    if (!validate()) {
      return;
    }

    setSubmitting(true);
    setApiError(null);

    try {
      const payload = convertFromQuote
        ? {
            quoteId: defaultQuoteId,
            dueDate,
            notes: notes.trim() || null,
          }
        : {
            clientId,
            date,
            dueDate,
            lineItems,
            notes: notes.trim() || null,
          };

      const response = await fetch('/api/invoices', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
      });

      const result = (await response.json()) as {
        _id?: string;
        success?: boolean;
        message?: string;
        data?: { _id?: string };
      };

      if (!response.ok) {
        throw new Error(result.message || t.createFailed);
      }

      const createdId = result._id || result.data?._id;
      toast.success(t.createSuccess);
      if (createdId) {
        router.push(`/invoices/${createdId}`);
      } else {
        router.push('/invoices');
      }
    } catch (error) {
      setApiError(error instanceof Error ? error.message : t.createFailed);
    } finally {
      setSubmitting(false);
    }
  }

  return (
    <section data-tour-invoice-form className="space-y-4 pb-24 lg:pb-6">
      <header className="rounded-xl border border-border/70 bg-linear-to-b from-background to-secondary/30 p-4 sm:p-5">
        <div className="mb-4 flex items-start justify-between gap-3">
          <div className="space-y-1">
            <button
              type="button"
              className="mb-1 inline-flex items-center gap-1.5 text-xs text-muted-foreground hover:text-foreground"
              onClick={() => router.push('/invoices')}
            >
              <FileTextIcon className="size-3" />
              {t.backToInvoices}
            </button>
            <h1 className="font-heading text-2xl font-semibold tracking-tight sm:text-3xl">{t.title}</h1>
            <p className="text-sm text-muted-foreground">{t.subtitle}</p>
          </div>
        </div>

        {convertFromQuote ? (
          <div className="rounded-lg border border-sky-300/60 bg-sky-50/60 px-3 py-2 text-sm text-sky-900 dark:border-sky-700/40 dark:bg-sky-950/30 dark:text-sky-200">
            <p className="font-medium">{t.fromQuoteTitle}</p>
            <p className="text-xs opacity-90">{t.fromQuoteText}</p>
          </div>
        ) : null}

        <div className="mt-3 grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
          <div className="space-y-1.5 rounded-lg border border-border/70 bg-background/80 p-3">
            <Label htmlFor="invoice-number">{t.invoiceNumber}</Label>
            <Input id="invoice-number" value={formatInvoiceDisplayNumber(locale, invoiceNumber)} readOnly className="bg-muted/40" />
            <p className="text-xs text-muted-foreground">{t.autoGenerated}</p>
          </div>

          <div className="space-y-1.5 rounded-lg border border-border/70 bg-background/80 p-3">
            <Label htmlFor="invoice-date">{t.date}</Label>
            <div className="relative">
              <CalendarDaysIcon className="pointer-events-none absolute right-3 top-1/2 size-4 -translate-y-1/2 text-muted-foreground" />
              <Input
                id="invoice-date"
                type="date"
                value={date}
                onChange={(event) => setDate(event.target.value)}
                className="pr-9"
                disabled={convertFromQuote}
              />
            </div>
            {errors.date ? <p className="text-xs text-destructive">{errors.date}</p> : null}
          </div>

          <div className="space-y-1.5 rounded-lg border border-border/70 bg-background/80 p-3">
            <Label htmlFor="invoice-due-date">{t.dueDate}</Label>
            <Input data-tour-invoice-due-date id="invoice-due-date" type="date" value={dueDate} onChange={(event) => setDueDate(event.target.value)} />
            {errors.dueDate ? <p className="text-xs text-destructive">{errors.dueDate}</p> : null}
          </div>
        </div>
      </header>

      {apiError ? <ErrorMessage message={apiError} /> : null}

      <div className="grid gap-4 lg:grid-cols-[1.5fr_1fr]">
        <div className="space-y-4">
          {!convertFromQuote ? (
            <section data-tour-invoice-client-step className="rounded-xl border border-border/70 bg-card p-4 shadow-sm">
              <h2 className="mb-3 inline-flex items-center gap-2 font-heading text-base font-semibold">
                <span className="flex size-6 items-center justify-center rounded-full bg-primary text-[11px] font-bold text-primary-foreground">{clientId ? '✓' : '1'}</span>
                <UserRoundIcon className="size-4 text-muted-foreground" />
                {t.client}
                <span className="text-xs font-normal text-muted-foreground">— {t.step1}</span>
              </h2>
              <ClientPicker value={clientId} onChange={setClientId} onClientSelected={() => undefined} />
              {errors.clientId ? <p className="mt-2 text-xs text-destructive">{errors.clientId}</p> : null}
            </section>
          ) : null}

          {!convertFromQuote ? (
            <section data-tour-invoice-items-step className="rounded-xl border border-border/70 bg-card p-4 shadow-sm">
              <h2 className="mb-3 inline-flex items-center gap-2 font-heading text-base font-semibold">
                <span className="flex size-6 items-center justify-center rounded-full bg-primary text-[11px] font-bold text-primary-foreground">{lineItems.length > 0 ? '✓' : '2'}</span>
                <FileTextIcon className="size-4 text-muted-foreground" />
                {t.lineItems}
                <span className="text-xs font-normal text-muted-foreground">— {t.step2}</span>
              </h2>
              <LineItemsBuilder lineItems={lineItems} onChange={setLineItems} />
              {errors.lineItems ? <p className="mt-2 text-xs text-destructive">{errors.lineItems}</p> : null}
            </section>
          ) : null}
        </div>

        <aside className="space-y-4 lg:sticky lg:top-20 lg:self-start">
          <div data-tour-invoice-create-action className="rounded-xl border border-border/70 bg-background/95 p-4 shadow-sm">
            <Button type="button" data-tour-invoice-create-button className="h-11 w-full rounded-xl text-sm font-semibold" disabled={submitting} onClick={handleSubmit}>
              {submitting ? t.creating : t.createInvoice}
            </Button>
          </div>

          {!convertFromQuote ? (
            <div data-tour-invoice-totals-step>
              <h2 className="mb-3 inline-flex items-center gap-2 font-heading text-base font-semibold">
                <span className="flex size-6 items-center justify-center rounded-full bg-primary text-[11px] font-bold text-primary-foreground">3</span>
                {t.step3}
              </h2>
              <QuoteTotals lineItems={lineItems} />
            </div>
          ) : null}

          <section className="rounded-xl border border-border/70 bg-card p-4 shadow-sm space-y-4">
            <h2 className="inline-flex items-center gap-2 font-heading text-base font-semibold">
              <span className="flex size-6 items-center justify-center rounded-full bg-primary text-[11px] font-bold text-primary-foreground">4</span>
              {t.step4}
            </h2>

            <div className="space-y-1.5">
              <Label htmlFor="invoice-notes" className="inline-flex items-center gap-2">
                <NotebookTextIcon className="size-4 text-muted-foreground" />
                {t.notes}
              </Label>
              <textarea
                id="invoice-notes"
                className="mt-1 min-h-28 w-full rounded-lg border border-input bg-background px-3 py-2 text-sm outline-none transition-colors focus-visible:border-ring focus-visible:ring-3 focus-visible:ring-ring/50"
                placeholder={t.notesPlaceholder}
                value={notes}
                onChange={(event) => setNotes(event.target.value)}
              />
            </div>
          </section>
        </aside>
      </div>
    </section>
  );
}
